// Minimal RFC 4180 CSV parser. Handles quoted fields, escaped quotes, and newlines inside quotes.
// Returns one object per data row, keyed by the trimmed header text.
export function parseCsv(text: string): Record<string, string>[] {
  const rows: string[][] = [];
  let field = '';
  let row: string[] = [];
  let inQuotes = false;

  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += c;
      }
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ',') {
      row.push(field);
      field = '';
    } else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else {
      field += c;
    }
  }
  if (field !== '' || row.length > 0) {
    row.push(field);
    rows.push(row);
  }

  const [header, ...body] = rows.filter((r) => !(r.length === 1 && r[0].trim() === ''));
  if (!header) return [];
  const keys = header.map((h) => h.trim());
  return body.map((r) => {
    const obj: Record<string, string> = {};
    keys.forEach((k, idx) => {
      obj[k] = (r[idx] ?? '').trim();
    });
    return obj;
  });
}
